async function startMusic() {

    try {

        await music.play();


        playButton.textContent =
            "❚❚";


        musicPlaying =
            true;

    }

    catch (error) {

        playButton.textContent =
            "▶";


        musicPlaying =
            false;

    }

}



playButton.addEventListener(
    "click",
    async function () {

        if (
            music.paused
        ) {

            try {

                await music.play();


                playButton.textContent =
                    "❚❚";


                musicPlaying =
                    true;

            }

            catch (error) {

                console.log(
                    "No se pudo reproducir la música."
                );

            }

        }

        else {

            music.pause();


            playButton.textContent =
                "▶";


            musicPlaying =
                false;

        }

    }
);



