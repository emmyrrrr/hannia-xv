/* VALIDAR */
/* ========================================== */

function validateAccess() {

    const folio =
        normalizeFolio(
            folioInput.value
        );

    const password =
        normalizePassword(
            passwordInput.value
        );


    if (!folio) {

        folioError.textContent =
            "Ingresa el folio de tu invitación.";

        return;
    }


    if (!invitados[folio]) {

        folioError.textContent =
            "No encontramos ese folio.";

        return;
    }


    if (!password) {

        folioError.textContent =
            "Ingresa la contraseña de tu invitación.";

        return;
    }


    const expectedPassword =
        normalizePassword(
            invitados[folio].password
        );


    if (
        password !==
        expectedPassword
    ) {

        folioError.textContent =
            "La contraseña no coincide con esta invitación.";

        return;
    }


    folioError.textContent =
        "";

    folioActual =
        folio;

    invitacionActual =
        invitados[folio];

    loadInvitation();

}


