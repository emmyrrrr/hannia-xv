const eventDate =
    new Date(
        2027,
        0,
        16,
        20,
        0,
        0
    );


function updateCountdown() {

    const now =
        new Date();


    let difference =
        eventDate - now;


    if (
        difference <= 0
    ) {

        document.getElementById(
            "countdown"
        ).innerHTML = `

            <div class="event-arrived">
                ¡Llegó el gran día!
            </div>

        `;

        return;

    }


    const days =
        Math.floor(
            difference /
            86400000
        );


    difference %=
        86400000;


    const hours =
        Math.floor(
            difference /
            3600000
        );


    difference %=
        3600000;


    const minutes =
        Math.floor(
            difference /
            60000
        );


    difference %=
        60000;


    const seconds =
        Math.floor(
            difference /
            1000
        );


    document.getElementById(
        "days"
    ).textContent =
        days;


    document.getElementById(
        "hours"
    ).textContent =
        String(hours)
            .padStart(
                2,
                "0"
            );


    document.getElementById(
        "minutes"
    ).textContent =
        String(minutes)
            .padStart(
                2,
                "0"
            );


    document.getElementById(
        "seconds"
    ).textContent =
        String(seconds)
            .padStart(
                2,
                "0"
            );

}


updateCountdown();


setInterval(
    updateCountdown,
    1000
);



