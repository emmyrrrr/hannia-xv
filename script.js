function renderAttendancePeople() {

    attendancePeople.innerHTML =
        "";


    invitacionActual.personas.forEach(
        function(persona,index) {

            const label =
                document.createElement(
                    "label"
                );


            label.className =
                "attendance-person";


            const input =
                document.createElement(
                    "input"
                );


            input.type =
                "checkbox";


            input.value =
                persona;


            input.id =
                `attendance-${index}`;


            const custom =
                document.createElement(
                    "span"
                );


            custom.className =
                "custom-checkbox";


            const name =
                document.createElement(
                    "span"
                );


            name.className =
                "attendance-person-name";


            name.textContent =
                persona;


            input.addEventListener(
                "change",
                function() {

                    label.classList.toggle(
                        "selected",
                        input.checked
                    );


                    updateAttendance();

                }
            );


            label.appendChild(
                input
            );


            label.appendChild(
                custom
            );


            label.appendChild(
                name
            );


            attendancePeople.appendChild(
                label
            );

        }
    );


    updateAttendance();

}



/* ========================================== */
/* OBTENER PERSONAS SELECCIONADAS */
/* ========================================== */

function getSelectedPeople() {

    return Array.from(

        attendancePeople.querySelectorAll(
            'input[type="checkbox"]:checked'
        )

    ).map(
        function(input) {

            return input.value;

        }
    );

}



/* ========================================== */
/* ACTUALIZAR CONFIRMACIÓN */
/* ========================================== */

function updateAttendance() {

    const seleccionados =
        getSelectedPeople();


    const cantidad =
        seleccionados.length;


    attendanceSummary.textContent =
        cantidad === 1
            ? "1 persona"
            : `${cantidad} personas`;


    if (
        cantidad === 0
    ) {

        whatsappButton.classList.add(
            "disabled"
        );


        whatsappButton.href =
            "#";


        confirmationWarning.textContent =
            "Selecciona quiénes asistirán para habilitar la confirmación.";


        return;

    }


    createWhatsappMessage(
        seleccionados
    );


    whatsappButton.classList.remove(
        "disabled"
    );


    confirmationWarning.textContent =

        cantidad === 1

            ? "Confirmarás la asistencia de 1 persona."

            : `Confirmarás la asistencia de ${cantidad} personas.`;

}



/* ========================================== */
/* MENSAJE WHATSAPP */
/* ========================================== */

