const carouselDots =
    document.getElementById(
        "carouselDots"
    );


if (
    carousel &&
    carouselPrev &&
    carouselNext &&
    carouselDots
) {

    const cards =
        Array.from(
            carousel.querySelectorAll(
                ".polaroid"
            )
        );


    let currentIndex =
        0;


    cards.forEach(
        function (
            card,
            index
        ) {

            const dot =
                document.createElement(
                    "button"
                );


            dot.type =
                "button";


            dot.className =
                index === 0
                    ? "dot active"
                    : "dot";


            dot.setAttribute(
                "aria-label",
                `Ir a la foto ${index + 1}`
            );


            dot.addEventListener(
                "click",
                function () {

                    goToSlide(
                        index
                    );

                }
            );


            carouselDots.appendChild(
                dot
            );

        }
    );


    const dots =
        Array.from(
            carouselDots.querySelectorAll(
                ".dot"
            )
        );



    function updateDots() {

        dots.forEach(
            function (
                dot,
                index
            ) {

                dot.classList.toggle(
                    "active",
                    index === currentIndex
                );

            }
        );

    }



    function goToSlide(index) {

        if (
            index < 0
        ) {

            index =
                cards.length - 1;

        }


        if (
            index >= cards.length
        ) {

            index =
                0;

        }


        currentIndex =
            index;


        const target =
            cards[currentIndex];


        const targetLeft =
            target.offsetLeft -
            carousel.clientWidth / 2 +
            target.offsetWidth / 2;


        carousel.scrollTo(
            {
                left:
                    targetLeft,

                behavior:
                    "smooth"
            }
        );


        updateDots();

    }



    carouselPrev.addEventListener(
        "click",
        function () {

            goToSlide(
                currentIndex - 1
            );

        }
    );



    carouselNext.addEventListener(
        "click",
        function () {

            goToSlide(
                currentIndex + 1
            );

        }
    );



    let scrollTimer;


    carousel.addEventListener(
        "scroll",
        function () {

            clearTimeout(
                scrollTimer
            );


            scrollTimer =
                setTimeout(
                    function () {

                        const carouselCenter =
                            carousel.scrollLeft +
                            carousel.clientWidth / 2;


                        let closestIndex =
                            0;


                        let closestDistance =
                            Infinity;


                        cards.forEach(
                            function (
                                card,
                                index
                            ) {

                                const cardCenter =
                                    card.offsetLeft +
                                    card.offsetWidth / 2;


                                const distance =
                                    Math.abs(
                                        carouselCenter -
                                        cardCenter
                                    );


                                if (
                                    distance <
                                    closestDistance
                                ) {

                                    closestDistance =
                                        distance;


                                    closestIndex =
                                        index;

                                }

                            }
                        );


                        currentIndex =
                            closestIndex;


                        updateDots();

                    },
                    100
                );

        },
        {
            passive: true
        }
    );


    window.addEventListener(
        "resize",
        function () {

            goToSlide(
                currentIndex
            );

        }
    );

}