/* NORMALIZAR FOLIO */
/* ========================================== */

function normalizeFolio(value) {

    if (!value) {
        return null;
    }

    let clean =
        value
            .trim()
            .toUpperCase()
            .replace(/\s+/g,"")
            .replace(/^HD/,"")
            .replace(/\D/g,"");

    if (!clean) {
        return null;
    }

    const number =
        parseInt(clean,10);

    if (isNaN(number)) {
        return null;
    }

    return (
        "HD" +
        String(number).padStart(3,"0")
    );

}


/* ========================================== */
/* NORMALIZAR CONTRASEÑA */
/* ========================================== */

function normalizePassword(value) {

    if (!value) {
        return "";
    }

    return value

        .trim()

        .toLowerCase()

        .normalize("NFD")

        .replace(
            /[\u0300-\u036f]/g,
            ""
        )

        .replace(
            /\s+/g,
            " "
        );

}


