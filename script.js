/* NORMALIZAR FOLIO */
/* ========================================== */

function normalizeFolio(value) {

    if (!value) {
        return null;
    }


    let clean =
        value
            .trim()
            .toUpperCase()
            .replace(/\s+/g,"")
            .replace(/^HD/,"")
            .replace(/\D/g,"");


    if (!clean) {
        return null;
    }


    const number =
        parseInt(
            clean,
            10
        );


    if (isNaN(number)) {
        return null;
    }


    return (
        "HD" +
        String(number)
            .padStart(
                3,
                "0"
            )
    );

}



/* ========================================== */
/* NORMALIZAR CONTRASEÑA */
/* ========================================== */

function normalizePassword(value) {

    if (!value) {
        return "";
    }


    return value

        .trim()

        .toLowerCase()

        .normalize("NFD")

        .replace(
            /[\u0300-\u036f]/g,
            ""
        )

        .replace(
            /\s+/g,
            " "
        );

}



/* ========================================== */
/* VALIDAR ACCESO */
/* ========================================== */

function validateAccess() {

    const folio =
        normalizeFolio(
            folioInput.value
        );


    const password =
        normalizePassword(
            passwordInput.value
        );


    if (!folio) {

        folioError.textContent =
            "Ingresa el folio de tu invitación.";

        return;

    }


    if (!invitados[folio]) {

        folioError.textContent =
            "No encontramos ese folio. Verifica los datos de tu invitación.";

        return;

    }


    if (!password) {

        folioError.textContent =
            "Ingresa la contraseña de tu invitación.";

        return;

    }


    const expectedPassword =
        normalizePassword(
            invitados[folio].password
        );


    if (
        password !==
        expectedPassword
    ) {

        folioError.textContent =
            "La contraseña no coincide con esta invitación.";

        return;

    }


    folioError.textContent =
        "";


    folioActual =
        folio;


    invitacionActual =
        invitados[folio];


    loadInvitation();

}



