/* NORMALIZAR FOLIO */
/* ========================================== */

function normalizeFolio(value) {

    if (!value) {
        return null;
    }

    let clean =
        value
            .trim()
            .toUpperCase();

    clean =
        clean.replace(
            /\s+/g,
            ""
        );

    clean =
        clean.replace(
            /^HD/,
            ""
        );

    clean =
        clean.replace(
            /\D/g,
            ""
        );

    if (!clean) {
        return null;
    }

    const number =
        parseInt(
            clean,
            10
        );

    if (isNaN(number)) {
        return null;
    }

    return (
        "HD" +
        String(number)
            .padStart(
                3,
                "0"
            )
    );

}



/* ========================================== */
/* VALIDAR FOLIO */
/* ========================================== */

function validateFolio() {

    const folio =
        normalizeFolio(
            folioInput.value
        );


    if (!folio) {

        folioError.textContent =
            "Ingresa el folio de tu invitación.";

        return;
    }


    if (!invitados[folio]) {

        folioError.textContent =
            "No encontramos ese folio. Verifica los datos de tu invitación.";

        return;
    }


    folioError.textContent =
        "";


    folioActual =
        folio;


    invitacionActual =
        invitados[folio];


    loadInvitation();

}



