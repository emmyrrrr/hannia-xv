function loadInvitation() {


    if (
        invitacionActual.tipo ===
        "familia"
    ) {

        guestName.textContent =
            "Familia " +
            invitacionActual.nombre;


        passesNumber.textContent =
            invitacionActual.pases;


        passesText.textContent =
            invitacionActual.pases === 1
                ? "lugar reservado"
                : "lugares reservados";


        attendanceBox
            .classList
            .remove(
                "hidden"
            );


        attendanceSelect.innerHTML = `

            <option value="">
                Selecciona una opción
            </option>

        `;


        for (
            let i = 1;
            i <= invitacionActual.pases;
            i++
        ) {

            const option =
                document.createElement(
                    "option"
                );


            option.value =
                i;


            option.textContent =
                i === 1
                    ? "1 persona"
                    : `${i} personas`;


            attendanceSelect.appendChild(
                option
            );

        }


        whatsappButton.style.opacity =
            "0.55";


        whatsappButton.style.pointerEvents =
            "none";


        whatsappButton.textContent =
            "CONFIRMAR POR WHATSAPP";


        confirmationWarning.textContent =
            "Primero selecciona cuántas personas asistirán.";

    }

    else {

        guestName.textContent =
            invitacionActual.nombre;


        passesNumber.textContent =
            "1";


        passesText.textContent =
            "lugar reservado";


        attendanceBox
            .classList
            .add(
                "hidden"
            );


        createIndividualWhatsapp();


        whatsappButton.style.opacity =
            "1";


        whatsappButton.style.pointerEvents =
            "auto";


        whatsappButton.textContent =
            "CONFIRMAR MI ASISTENCIA";


        confirmationWarning.textContent =
            "Esta invitación corresponde a 1 persona.";

    }


    familyFolio.textContent =
        folioActual;


    renderAssignedTable();


    folioScreen
        .classList
        .remove(
            "active"
        );


    folioScreen
        .classList
        .add(
            "hidden"
        );


    invitationContent
        .classList
        .add(
            "active"
        );


    window.scrollTo(
        0,
        0
    );


    startMusic();

}



