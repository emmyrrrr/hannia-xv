const observer =
    new IntersectionObserver(

        function (entries) {

            entries.forEach(

                function (entry) {

                    if (
                        entry.isIntersecting
                    ) {

                        entry
                            .target
                            .classList
                            .add(
                                "visible"
                            );

                    }

                }

            );

        },

        {
            threshold:
                0.12
        }

    );


document
    .querySelectorAll(
        ".reveal"
    )
    .forEach(

        function (element) {

            observer.observe(
                element
            );

        }

    );



